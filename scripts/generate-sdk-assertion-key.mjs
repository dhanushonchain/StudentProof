#!/usr/bin/env node
// Generate an Ed25519 assertion-signing keypair for the SDK v2 flow.
//
// Usage:
//   node scripts/generate-sdk-assertion-key.mjs [--out <path>]
//
// Output (exactly once — the private key is never stored anywhere by this
// script, never logged, and never committed):
//   SDK_ASSERTION_ED25519_PRIVATE_KEY="<pem with literal \n escapes>"
//   SDK_ASSERTION_ED25519_KID="<rfc7638 thumbprint>"
//   <public JWK JSON, for SDK_ASSERTION_ED25519_PREV_PUBLIC_JWK during rotation>
//
// With --out, the same block is written to a NEW file created mode 0600
// instead of stdout. Rotation: generate a fresh pair, deploy its PEM+KID as
// current, keep the old PUBLIC JWK as PREV for one overlap window, then drop
// PREV. Pairwise subjects are unaffected (separate SDK_PAIRWISE_SECRET).
//
// Implementation note: the keypair is generated by the repo's own
// lib/sdk-crypto.ts (compiled with the repo's tsc into a temp dir first),
// so the kid/thumbprint format cannot drift from what the server verifies.
import { existsSync, openSync, writeFileSync, chmodSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";

const require = createRequire(join(process.cwd(), "package.json"));

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

const args = process.argv.slice(2);
let out = null;
for (let i = 0; i < args.length; i += 1) {
  if (args[i] === "--out") out = args[++i];
  else if (args[i] === "--help" || args[i] === "-h") {
    console.log("Generate an Ed25519 SDK assertion-signing keypair. [--out <new-0600-file>]");
    process.exit(0);
  } else fail(`Unknown argument: ${args[i]}`);
}
if (out && existsSync(out)) fail(`refusing: --out target already exists (${out}).`);

const dir = mkdtempSync(join(tmpdir(), "sp-keygen-"));
try {
  execFileSync(
    "./node_modules/.bin/tsc",
    [
      "lib/sdk-crypto.ts",
      "--outDir",
      dir,
      "--module",
      "commonjs",
      "--target",
      "es2020",
      "--moduleResolution",
      "node",
      "--skipLibCheck",
      "--esModuleInterop",
    ],
    { stdio: "pipe" },
  );
  const crypto = require(join(dir, "sdk-crypto.js"));
  const { privateKeyPem, publicJwk, kid } = crypto.generateAssertionKeypair();
  const oneLinePem = privateKeyPem.replace(/\n/g, "\\n");
  const block = [
    "# SDK v2 assertion-signing keypair — generated once, just now.",
    "# Private PEM: server-only env (never commit, never ship to browsers).",
    `# SDK_ASSERTION_ED25519_PRIVATE_KEY="${oneLinePem}"`,
    `SDK_ASSERTION_ED25519_KID="${kid}"`,
    `# Public JWK (published at GET /api/sdk/jwks; keep as PREV during rotation):`,
    `# SDK_ASSERTION_ED25519_PREV_PUBLIC_JWK='${JSON.stringify(publicJwk)}'`,
    `PUBLIC_JWK=${JSON.stringify(publicJwk)}`,
    "",
  ].join("\n");
  if (!out) {
    console.log("");
    console.log("  SDK assertion-signing keypair — shown exactly once:");
    console.log("");
    console.log(block);
  } else {
    const fd = openSync(out, "wx", 0o600);
    writeFileSync(fd, block, "utf8");
    chmodSync(out, 0o600);
    console.log(`Keypair block written once to ${out} (mode 0600).`);
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error));
} finally {
  rmSync(dir, { recursive: true, force: true });
}
